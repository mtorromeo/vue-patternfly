    <pre v-md>
      ## Differences from patternfly-react
      - The expanded state of `pf-notification-drawer-group` is bound with `v-model:expanded` and managed internally when unbound (`isExpanded` + `onExpand`); its content is only rendered while expanded.
      - `isRead` is `read`, `isHoverable` is `hoverable` and `actionHasNoOffset` is `action-no-offset`; `isHidden` of `pf-notification-drawer-list` is the native `hidden` attribute.
      - The `icon` prop of `pf-notification-drawer-list-item-header` and the `timestamp` of `pf-notification-drawer-list-item-body` are also slots, like the `title` of `pf-notification-drawer-group`.
      See [common differences from patternfly-react](#/).

