<script lang="ts" setup>
import EllipsisVerticalIcon from '@vue-patternfly/icons/ellipsis-vertical-icon';
import MagnifyingGlassIcon from '@vue-patternfly/icons/magnifying-glass-icon';
import { createReusableTemplate } from '@vueuse/core';
import { ref } from 'vue';

const [DefineKebab, Kebab] = createReusableTemplate<{ label: string }>();

type Notification = {
  variant?: 'success' | 'danger' | 'warning' | 'info' | 'custom';
  title: string;
  srTitle: string;
  timestamp: string;
  description: string;
  read?: boolean;
  truncateTitle?: number;
};

const longDanger =
  'This is a danger notification description. This is a long description to show how the title will wrap if it is long and wraps to multiple lines.';

const info: Notification = {
  variant: 'info',
  title: 'Unread info notification title',
  srTitle: 'Info notification:',
  timestamp: '5 minutes ago',
  description: 'This is an info notification description.',
};
const danger: Notification = {
  variant: 'danger',
  title:
    'Unread danger notification title. This is a long title to show how the title will wrap if it is long and wraps to multiple lines.',
  srTitle: 'Danger notification:',
  timestamp: '10 minutes ago',
  description: longDanger,
};
const warning: Notification = {
  variant: 'warning',
  title: 'Read warning notification title',
  srTitle: 'Warning notification:',
  timestamp: '20 minutes ago',
  description: 'This is a warning notification description.',
  read: true,
};
const success: Notification = {
  variant: 'success',
  title: 'Read success notification title',
  srTitle: 'Success notification:',
  timestamp: '30 minutes ago',
  description: 'This is a success notification description.',
  read: true,
};

const basicNotifications: Notification[] = [
  info,
  danger,
  {
    ...danger,
    title:
      'Unread danger notification title. This is a long title to show how the title will be truncated if it is long and will be shown in a single line.',
    truncateTitle: 1,
  },
  warning,
  success,
  {
    title: 'Read (default) notification title',
    srTitle: 'notification:',
    timestamp: '35 minutes ago',
    description: 'This is a default notification description.',
    read: true,
  },
];

const groupNotifications: Notification[] = [info, danger, warning, success];

const lightweightNotifications: Notification[] = [
  { ...info, title: 'Info notification title' },
  {
    ...danger,
    title:
      'Danger notification title. This is a long title to show how the title will wrap if it is long and wraps to multiple lines.',
  },
  { ...warning, title: 'Warning notification title', read: false },
  { ...success, title: 'Success notification title', read: false },
];

// like upstream, expanding a group collapses the others
const expandedGroup = ref(2);
const expandedLightweightGroup = ref(2);
</script>
